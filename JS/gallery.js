/* Gallery code */
const grid = document.getElementById("grid");
const countEl = document.getElementById("count");
const lb = document.getElementById("lb");
const lbImg = document.getElementById("lbImg");
const lbCap = document.getElementById("lbCap");

const visible = images; // all images, in array order
let current = 0; // index of the photo shown in the viewer
let lastFocus = null;

// Draw a simple placeholder if an image file can't be loaded
function placeholder(label) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600">
    <rect width="800" height="600" fill="#dfe6d9"/>
    <path d="M400 190 L520 390 H280 Z" fill="#4f7a4a"/>
    <rect x="392" y="390" width="16" height="40" fill="#1e3a2f"/>
    <text x="400" y="490" font-family="sans-serif" font-size="30" text-anchor="middle" fill="#1e3a2f">${label.replace(/&/g, "&amp;").replace(/</g, "&lt;")}</text>
  </svg>`;
  return "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg);
}
function withFallback(img, item) {
  img.onerror = () => {
    img.onerror = null;
    img.src = placeholder(item.title);
  };
}

function render() {
  grid.innerHTML = "";
  countEl.textContent = `${visible.length} photo${visible.length === 1 ? "" : "s"}`;

  if (!visible.length) {
    grid.innerHTML = '<p class="empty">No photos yet.</p>';
    return;
  }

  const frag = document.createDocumentFragment();
  visible.forEach((item, idx) => {
    const card = document.createElement("button");
    card.type = "button";
    card.className = "card";
    card.setAttribute("aria-label", `Open photo: ${item.title}`);

    const img = document.createElement("img");
    img.src = item.src;
    img.alt = item.alt || item.title;
    img.loading = "lazy";
    withFallback(img, item);

    const meta = document.createElement("span");
    meta.className = "meta";
    meta.innerHTML = '<span class="title"></span>';
    meta.querySelector(".title").textContent = item.title;

    card.append(img, meta);
    card.addEventListener("click", () => openViewer(idx));
    frag.appendChild(card);
  });
  grid.appendChild(frag);
}

function showPhoto() {
  const item = visible[current];
  lbImg.src = item.src;
  lbImg.alt = item.alt || item.title;
  withFallback(lbImg, item);
  lbCap.innerHTML = "<strong></strong><span></span>";
  lbCap.querySelector("strong").textContent = item.title;
  lbCap.querySelector("span").textContent =
    (item.caption ? item.caption + " " : "") +
    `(${current + 1} of ${visible.length})`;
}

function openViewer(idx) {
  lastFocus = document.activeElement;
  current = idx;
  showPhoto();
  lb.classList.add("open");
  document.body.style.overflow = "hidden";
  lb.querySelector(".close").focus();
}
function closeViewer() {
  lb.classList.remove("open");
  document.body.style.overflow = "";
  if (lastFocus) lastFocus.focus();
}
function step(dir) {
  current = (current + dir + visible.length) % visible.length;
  showPhoto();
}

lb.querySelector(".close").addEventListener("click", closeViewer);
lb.querySelector(".prev").addEventListener("click", () => step(-1));
lb.querySelector(".next").addEventListener("click", () => step(1));
lb.addEventListener("click", (e) => {
  if (e.target === lb) closeViewer();
});
document.addEventListener("keydown", (e) => {
  if (!lb.classList.contains("open")) return;
  if (e.key === "Escape") closeViewer();
  if (e.key === "ArrowLeft") step(-1);
  if (e.key === "ArrowRight") step(1);
});

render();
